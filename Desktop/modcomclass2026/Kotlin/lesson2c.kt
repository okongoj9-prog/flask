fun main(){
    // if... else if ... else conditional statement
    // used in evaluating multiple conditions until a given condition is met and if there is no condition met, it defaults tothe else part

    val number = 0

    if (number > 0){
        println("The number is positive")
    }
    else if(number == 0){
        println("The number is Zero ")
    }
    else(
        println("The number is negative")
    )
}